// icon renders an inline SVG icon: {{icon "users"}}. Size and color come
// from CSS (.icon), so it matches the text around it.
func icon(name string) (template.HTML, error) {
	paths, ok := iconPaths[name]
	if !ok {
		return "", fmt.Errorf("unknown icon %q", name)
	}
	return template.HTML(`<svg class="icon" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">` + paths + `</svg>`), nil
}
